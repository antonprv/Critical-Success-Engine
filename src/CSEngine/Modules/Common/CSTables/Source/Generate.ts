import { Access } from "./Format.ts";
import type { CompiledKey, CompiledTables, CompiledValue } from "./Tables.ts";

/**
 * The TypeScript a project reaches its tables with
 * (Source/Generated/CSTables.ts):
 *
 * ```ts
 * CSTables.UiNames.MenuTitle          // the text in the language current now
 * CSTables.MenuTitle                  // the same, if no other table has it
 * CSTables.UiNames.Greeting({ name }) // a key with arguments: a function
 * CSTables.UiNames.Coins(3)           // a plural key: the count first
 * CSTablesRuntime.SetLanguage("en")   // the languages, the current one
 * ```
 *
 * Each language is a module of its own (CSTables.<language>.ts): the base one
 * is imported, the others are loaded the first time they are chosen, so a build
 * carries the languages it needs only when they are needed.
 */

export interface GeneratedFiles {
	/** File name → text. */
	Files: Record<string, string>;
}

const Header =
	"// Generated by @cse/cstables from the project's .cstables files: don't "
		+ "edit, it is written again on every build.\n";

/**
 * Names the generated object can't give a key: the runtime's own and
 * JavaScript's.
 */
const Reserved = new Set(
	[
		"constructor",
		"prototype",
		"__proto__",
		"toString",
		"valueOf",
		"hasOwnProperty",
	],
);

/**
 * A value as a doc comment line (what the key says in the base language, which
 * has every key).
 */
function Doc( value: CompiledValue ): string {
	const base = value!;
	const text = typeof base === "string"
		? base
		: ( base.other ?? Object.values( base )[0] ?? "" );

	return text.replace( /\*\//g, "*\\/" ).replace( /\r?\n/g, " " )
		.slice( 0, 120 );
}

function Member(
	key: CompiledKey,
	id: number,
	value: CompiledValue,
	indent: string,
): string {
	const internal = key.Access === Access.Internal ? " @internal" : "";
	const head = `${ indent }/** ${ Doc( value ) }${ internal } */\n`
		+ `${ indent }${ Property( key.Key ) }`;
	const Shape = ( names: string[] ): string => names
		.map( ( name ) => `${ Property( name ) }: unknown` ).join( "; " );

	if ( key.Plural ) {
		const extra = key.Arguments.filter( ( name ) => name !== "count" );

		if ( extra.length === 0 ) {
			return `${ head }: ( count: number ): string => `
				+ `L.Plural( ${ id }, count ),\n`;
		}
		return `${ head }: ( count: number, args: { ${ Shape( extra ) }; } )`
			+ `: string => L.Plural( ${ id }, count, args ),\n`;
	}
	if ( key.Arguments.length === 0 ) {
		// A getter: read, it gives the text of the language current then.
		return `${ indent }/** ${ Doc( value ) }${ internal } */\n`
			+ `${ indent }get ${ Property( key.Key ) }(): string `
			+ `{ return L.Get( ${ id } ); },\n`;
	}
	if ( key.Arguments.every( ( name ) => /^\d+$/.test( name ) ) ) {
		const count = Math.max( ...key.Arguments.map( Number ) ) + 1;
		const names = Array.from( { length: count }, ( _, n ) => `arg${ n }` );
		const params = names.map( ( name ) => `${ name }: unknown` )
			.join( ", " );

		return `${ head }: ( ${ params } ): string => `
			+ `L.Format( ${ id }, [ ${ names.join( ", " ) } ] ),\n`;
	}
	return `${ head }: ( args: { ${ Shape( key.Arguments ) }; } ): string => `
		+ `L.Format( ${ id }, args ),\n`;
}

/**
 * The keys that also get the short access: generated, in one table only, not a
 * table's name.
 */
export function ShortKeys( compiled: CompiledTables ): Set<string> {
	const keys = compiled.Keys.filter( ( key ) => key.Access !== Access.None );
	const tables = new Set( keys.map( ( key ) => key.Table ) );
	const counts = new Map<string, number>();

	for ( const key of keys ) {
		counts.set(
			key.Key,
			( counts.get( key.Key ) ?? 0 ) + 1,
		);
	}
	return new Set(
		keys.filter(
			( key ) => counts.get( key.Key ) === 1 && !tables.has( key.Key ),
		).map( ( key ) => key.Key ),
	);
}

function Property( name: string ): string {
	return /^\d/.test( name ) || Reserved.has( name )
		? JSON.stringify( name )
		: name;
}

/**
 * The generated files: CSTables.ts and one CSTables.<language>.ts a language.
 * `shortKeys`: the keys that also get the short access (in no other table, not
 * a table's name). `runtime`: where the runtime is imported from.
 */
export function GenerateTypeScript(
	compiled: CompiledTables,
	shortKeys: ReadonlySet<string>,
	runtime = "@cse/cstables",
): GeneratedFiles {
	const files: Record<string, string> = {};
	const base = compiled.BaseLanguage;
	const ids = compiled.Keys.map( ( key, id ) => ( { Key: key, Id: id } ) )
		.filter( ( { Key } ) => Key.Access !== Access.None );
	const tables = [ ...new Set( ids.map( ( { Key } ) => Key.Table ) ) ];
	const ModuleName = ( language: string ): string => `CSTables.${ language }`;
	let text = Header;

	text += "import { Localization, type CompiledValue } "
		+ `from ${ JSON.stringify( runtime ) };\n`;
	text += `import Base from "./${ ModuleName( base ) }.ts";\n\n`;
	text += "/** The tables' runtime: the languages, the current one "
		+ "(SetLanguage), its change (OnLanguageChanged). */\n";
	text += "export const CSTablesRuntime = new Localization( {\n";
	text += `\tBaseLanguage: ${ JSON.stringify( base ) },\n`;
	text += `\tLanguages: ${ JSON.stringify( compiled.Languages ) },\n`;
	const names = compiled.Keys.map( ( key ) => `${ key.Table }.${ key.Key }` );

	text += `\tNames: ${ JSON.stringify( names ) },\n`;
	text += "}, {\n";
	text += `\t${ JSON.stringify( base ) }: Base,\n`;
	for ( const language of compiled.Languages.filter( ( l ) => l !== base ) ) {
		text += `\t${ JSON.stringify( language ) }: async () => ( await `
			+ `import( "./${ ModuleName( language ) }.ts" ) ).default as `
			+ "readonly CompiledValue[],\n";
	}
	text += "} );\n\nconst L = CSTablesRuntime;\n\n";
	text += "/** Every table's keys (CSTables.Table.Key), and the keys no "
		+ "other table has right here (CSTables.Key). */\n";
	text += "export const CSTables = {\n";
	for ( const table of tables ) {
		text += `\t${ table }: {\n`;
		for ( const { Key, Id } of ids.filter(
			( { Key: key } ) => key.Table === table,
		) ) {
			text += Member( Key, Id, compiled.Values[base]![Id]!, "\t\t" );
		}
		text += "\t},\n";
	}
	for ( const { Key, Id } of ids.filter(
		( { Key: key } ) => shortKeys.has( key.Key ),
	) ) {
		text += Member( Key, Id, compiled.Values[base]![Id]!, "\t" );
	}
	text += "};\n";
	files["CSTables.ts"] = text;
	for ( const language of compiled.Languages ) {
		const values = JSON.stringify( compiled.Values[language], null, "\t" );

		files[`${ ModuleName( language ) }.ts`] = `${ Header }`
			+ "import type { CompiledValue } "
			+ `from ${ JSON.stringify( runtime ) };\n\n`
			+ `/** ${ language }: the value of each key, by id `
			+ "(null: not translated). */\n"
			+ `export default ${ values } as readonly CompiledValue[];\n`;
	}
	return { Files: files };
}
