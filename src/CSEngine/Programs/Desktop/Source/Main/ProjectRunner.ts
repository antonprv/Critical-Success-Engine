import { spawn, type ChildProcess } from "node:child_process";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { readFile } from "node:fs/promises";
import { createServer, get, type Server } from "node:http";
import { createServer as createSocketServer, type AddressInfo } from "node:net";
import { basename, dirname, extname, join, resolve, sep } from "node:path";
import { Task, TaskCompletionSource } from "@cse/task";
import { PackageApp, type PackageOptions } from "./Packager";

export type BuildConfiguration = "Dev" | "Prod";
/** Web: the static site. Desktop: the same site plus an Electron shell that opens it in a window (run with `electron .` in the folder). */
export type BuildPlatform = "Web" | "Desktop";
/** How the project browser runs a project: the dev server in a browser, or a finished build of a platform and configuration. */
export type RunMode = "dev" | "web:dev" | "web:prod" | "desktop:dev" | "desktop:prod";
export type RunAvailability = Record<RunMode, boolean>;

const BuildModes: Record<Exclude<RunMode, "dev">, { Platform: BuildPlatform; Configuration: BuildConfiguration; }> = {
	"web:dev": { Platform: "Web", Configuration: "Dev" },
	"web:prod": { Platform: "Web", Configuration: "Prod" },
	"desktop:dev": { Platform: "Desktop", Configuration: "Dev" },
	"desktop:prod": { Platform: "Desktop", Configuration: "Prod" },
};

export interface ProjectRunnerOptions {
	/** The engine's Vite project (src/CSEngine/Core): it builds the project named by CSE_PROJECT. */
	CoreDirectory: string;
	/** Shows a page in the system's browser. */
	Open(url: string): void | Promise<void>;
	/** The Electron executable that runs a Desktop build (the desktop app's own by default). */
	ElectronPath?: string;
	/** Tests replace the process spawner. */
	Spawn?: typeof spawn;
	/** Packages a Desktop build into an executable (electron-builder by default; tests replace it). */
	Package?: (options: PackageOptions) => Promise<string>;
	/** The platform the executable is made for (this machine's); only Windows ones are made yet (S6-07). */
	Platform?: NodeJS.Platform;
	/** How often and how many times to ask the dev server whether it is up (500 ms, 120 times: a minute). */
	DevPollMs?: number;
	DevPollAttempts?: number;
}

const MimeTypes: Record<string, string> = {
	".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".mjs": "text/javascript; charset=utf-8",
	".css": "text/css; charset=utf-8", ".json": "application/json", ".csedata": "application/json", ".map": "application/json",
	".wasm": "application/wasm", ".svg": "image/svg+xml", ".png": "image/png", ".jpg": "image/jpeg", ".webp": "image/webp",
	".glb": "model/gltf-binary", ".gltf": "model/gltf+json", ".woff2": "font/woff2", ".txt": "text/plain; charset=utf-8",
};

/** A project's finished build: Binaries/<Web|Desktop>/<Dev|Prod> next to the .cseproject, so platforms never overwrite each other. */
export const BuildDirectory = (file: string, platform: BuildPlatform, configuration: BuildConfiguration): string => join(dirname(file), "Binaries", platform, configuration);
/** Where a Desktop build's Windows executable goes: Binaries/Windows/<Dev|Prod>. */
export const ExecutableDirectory = (file: string, configuration: BuildConfiguration): string => join(dirname(file), "Binaries", "Windows", configuration);
const HasBuild = (directory: string): boolean => existsSync(join(directory, "index.html"));
/** pnpm's command on a platform (Windows runs its .cmd). */
export const PnpmCommand = (platform: NodeJS.Platform): string => (platform === "win32" ? "pnpm.cmd" : "pnpm");
const Pnpm = PnpmCommand(process.platform);

//#region static hosting

/** Serves a folder on 127.0.0.1 (a game's workers and wasm need http, not file://). Port 0: any free one. */
export async function ServeDirectory(root: string): Promise<{ Url: string; Server: Server; }> {
	const base = resolve(root);
	const server = createServer((request, response) => {
		void (async () => {
			try {
				const path = decodeURIComponent(request.url!.split("?")[0]!); // a server request always has its url
				const file = resolve(base, `.${path.endsWith("/") ? `${path}index.html` : path}`);
				if (file !== base && !file.startsWith(base + sep)) { response.writeHead(403).end(); return; }
				const body = await readFile(file);
				response.writeHead(200, { "Content-Type": MimeTypes[extname(file).toLowerCase()] ?? "application/octet-stream" }).end(body);
			} catch {
				response.writeHead(404).end();
			}
		})();
	});
	const listening = new TaskCompletionSource();
	server.listen(0, "127.0.0.1", () => listening.TrySetResult());
	await listening.Task;
	return { Url: `http://127.0.0.1:${(server.address() as AddressInfo).port}/`, Server: server };
}

