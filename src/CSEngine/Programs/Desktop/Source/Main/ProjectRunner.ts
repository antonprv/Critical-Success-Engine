/** Runs and builds projects for the project browser, with the Core's Vite (CSE_PROJECT names the project, CSE_OUT_DIR where the site goes). */
export class ProjectRunner {
	private readonly _spawn: typeof spawn;
	private readonly _dev = new Map<string, { Process: ChildProcess; Url: string; }>();
	private readonly _hosted = new Map<string, { Url: string; Server: Server; }>();

	public constructor(private readonly _options: ProjectRunnerOptions) {
		this._spawn = _options.Spawn ?? spawn;
	}

	/** Dev is always possible; a build mode only when Binaries/<Web|Desktop>/<Dev|Prod> holds that build (a Desktop one with its Electron shell). */
	public Availability(file: string): RunAvailability {
		const built = (mode: Exclude<RunMode, "dev">): boolean => {
			const { Platform, Configuration } = BuildModes[mode];
			const directory = BuildDirectory(file, Platform, Configuration);
			return HasBuild(directory) && (Platform === "Web" || existsSync(join(directory, "electron-main.cjs")));
		};
		return { "dev": existsSync(file), "web:dev": built("web:dev"), "web:prod": built("web:prod"), "desktop:dev": built("desktop:dev"), "desktop:prod": built("desktop:prod") };
	}

	/** dev: the dev server starts (once per project) and the page opens in the browser. Web: the build is hosted and opened in the browser. Desktop: the build opens in its own Electron window. */
	public async Run(file: string, mode: RunMode): Promise<void> {
		if (mode === "dev") {
			await this._options.Open(await this.StartDev(file));
			return;
		}
		const { Platform, Configuration } = BuildModes[mode];
		const directory = BuildDirectory(file, Platform, Configuration);
		if (!this.Availability(file)[mode]) throw new Error(`There is no ${Platform} ${Configuration} build in ${directory}: build the project first`);
		if (Platform === "Desktop") {
			const child = this._spawn(this._options.ElectronPath ?? process.execPath, [directory], { cwd: directory, env: { ...process.env, ELECTRON_RUN_AS_NODE: undefined }, stdio: "ignore", detached: true });
			child.once("error", () => undefined);
			child.unref();
			return;
		}
		let hosted = this._hosted.get(directory);
		if (!hosted) this._hosted.set(directory, hosted = await ServeDirectory(directory));
		await this._options.Open(hosted.Url);
	}

	/** Builds the project into Binaries/<platform>/<configuration> (emptied first); for Desktop also writes the Electron shell. */
	public async Build(file: string, platform: BuildPlatform, configuration: BuildConfiguration): Promise<{ Directory: string; }> {
		const directory = BuildDirectory(file, platform, configuration);
		const modeArguments = configuration === "Dev" ? ["--mode", "development"] : [];
		await this.Exec(["exec", "vite", "build", ...modeArguments], { CSE_PROJECT: file, CSE_OUT_DIR: directory });
		if (!HasBuild(directory)) throw new Error(`The build finished but ${directory} has no index.html`);
		if (platform === "Desktop") WriteElectronShell(directory, basename(file, ".cseproject"));
		// A server of the old files would serve the folder as it is now, which is fine; nothing to restart.
		return { Directory: directory };
	}

	public Dispose(): void {
		for (const { Process } of this._dev.values()) Process.kill();
		for (const { Server } of this._hosted.values()) Server.close();
		this._dev.clear();
		this._hosted.clear();
	}

	private async StartDev(file: string): Promise<string> {
		const running = this._dev.get(file);
		if (running && running.Process.exitCode === null) return running.Url;
		const port = await FreePort();
		const url = `http://127.0.0.1:${port}/`;
		const child = this._spawn(Pnpm, ["exec", "vite", "--host", "127.0.0.1", "--port", String(port)], {
			cwd: this._options.CoreDirectory, env: { ...process.env, CSE_PROJECT: file }, stdio: "ignore", shell: process.platform === "win32",
		});
		this._dev.set(file, { Process: child, Url: url });
		let failure: string | null = null;
		child.once("error", (error) => { failure = error.message; });
		child.once("exit", (code) => { failure ??= `the dev server exited with code ${code}`; this._dev.delete(file); });
		for (let attempt = 0; attempt < 120; attempt++) {
			if (failure !== null) throw new Error(`The dev server did not start: ${failure}`);
			if (await Responds(url)) return url;
			await new Promise((done) => setTimeout(done, 500));
		}
		child.kill();
		throw new Error("The dev server did not answer in 60 seconds");
	}

	/** Runs `pnpm <args>` in the Core; fails with the end of its output. */
	private Exec(args: string[], env: Record<string, string>): Promise<void> {
		return new Promise((done, fail) => {
			const child = this._spawn(Pnpm, args, { cwd: this._options.CoreDirectory, env: { ...process.env, ...env }, stdio: ["ignore", "pipe", "pipe"], shell: process.platform === "win32" });
			let tail = "";
			const keep = (chunk: Buffer): void => { tail = (tail + chunk.toString()).slice(-2000); };
			child.stdout?.on("data", keep);
			child.stderr?.on("data", keep);
			child.once("error", (error) => fail(new Error(`Could not start pnpm: ${error.message}`)));
			child.once("exit", (code) => (code === 0 ? done() : fail(new Error(`The build failed (exit code ${code}):\n${tail.trim()}`))));
		});
	}
}

function FreePort(): Promise<number> {
	return new Promise((done, fail) => {
		const probe = createSocketServer();
		probe.once("error", fail);
		probe.listen(0, "127.0.0.1", () => {
			const address = probe.address();
			probe.close(() => done(typeof address === "object" && address ? address.port : 0));
		});
	});
}

function Responds(url: string): Promise<boolean> {
	return new Promise((done) => {
		const request = get(url, (response) => { response.resume(); done((response.statusCode ?? 500) < 500); });
		request.once("error", () => done(false));
		request.setTimeout(1000, () => { request.destroy(); done(false); });
	});
}
