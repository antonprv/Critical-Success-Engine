const ElectronMain = `// Generated by the Critical Success Engine's Build (Electron). Run it with: electron . (or the packaged .exe).
// --cse-uncapped: no frame-rate limit (the perf harness); --cse-smoke <seconds>: quit with 0 that long after the page
// loaded, 1 if it didn't (the packaging smoke test); --cse-profile <folder>: keep settings, saves and logs there.
const { app, BrowserWindow } = require("electron");
const { createServer } = require("node:http");
const { readFile } = require("node:fs/promises");
const { appendFileSync, mkdirSync } = require("node:fs");
const { extname, join, resolve, sep } = require("node:path");
const Mime = ${JSON.stringify(MimeTypes)};
const root = resolve(__dirname);
const argument = (name) => { const at = process.argv.indexOf(name); return at < 0 ? null : (process.argv[at + 1] ?? ""); };
if (argument("--cse-profile")) app.setPath("userData", resolve(argument("--cse-profile")));
if (!app.requestSingleInstanceLock()) { app.quit(); }
const logs = join(app.getPath("userData"), "logs");
const log = (line) => { try { mkdirSync(logs, { recursive: true }); appendFileSync(join(logs, "main.log"), new Date().toISOString() + " " + line + "\\n"); } catch { /* no log */ } };
process.on("uncaughtException", (error) => { log("uncaught: " + (error.stack || error.message)); app.exit(1); });
if (argument("--cse-uncapped") !== null) {
	app.commandLine.appendSwitch("disable-frame-rate-limit");
	app.commandLine.appendSwitch("disable-gpu-vsync");
}
app.commandLine.appendSwitch("disable-renderer-backgrounding");
let main = null;
app.on("second-instance", () => { if (main) { if (main.isMinimized()) main.restore(); main.focus(); } });
const server = createServer((request, response) => {
	(async () => {
		try {
			const path = decodeURIComponent((request.url || "/").split("?")[0]);
			const file = resolve(root, "." + (path.endsWith("/") ? path + "index.html" : path));
			if (file !== root && !file.startsWith(root + sep)) { response.writeHead(403).end(); return; }
			const body = await readFile(file);
			response.writeHead(200, { "Content-Type": Mime[extname(file).toLowerCase()] || "application/octet-stream" }).end(body);
		} catch { response.writeHead(404).end(); }
	})();
});
server.listen(0, "127.0.0.1", () => {
	app.whenReady().then(() => {
		main = new BrowserWindow({ width: 1280, height: 720, autoHideMenuBar: true, webPreferences: { contextIsolation: true, nodeIntegration: false, sandbox: true } });
		const smoke = argument("--cse-smoke");
		if (smoke !== null) {
			main.webContents.once("did-finish-load", () => setTimeout(() => { log("smoke: ok"); app.exit(0); }, Number(smoke || 10) * 1000));
			main.webContents.once("did-fail-load", (_event, code, reason) => { log("smoke: load failed " + code + " " + reason); app.exit(1); });
		}
		// A crashed page is logged and loaded again rather than left blank.
		main.webContents.on("render-process-gone", (_event, details) => { log("page gone: " + details.reason); if (details.reason !== "clean-exit") main.reload(); });
		main.loadURL("http://127.0.0.1:" + server.address().port + "/");
		log("started " + app.getVersion());
	});
});
app.on("window-all-closed", () => { server.close(); app.quit(); });
`;

/** Puts an Electron shell next to a built site: electron-main.cjs and the package.json that names it. */
export function WriteElectronShell(directory: string, projectName: string): void {
	mkdirSync(directory, { recursive: true });
	writeFileSync(join(directory, "electron-main.cjs"), ElectronMain);
	writeFileSync(join(directory, "package.json"), `${JSON.stringify({ name: projectName.toLowerCase(), version: "1.0.0", main: "electron-main.cjs" }, null, 2)}\n`);
}

