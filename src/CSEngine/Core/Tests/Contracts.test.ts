import { afterEach, describe, expect, it, vi } from "vitest";
import {
	existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync,
	writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import type { ResolvedConfig, ViteDevServer } from "vite";
import {
	ContractsPlugin, GenerateContracts,
} from "../BuildTools/ContractsPlugin";
import { CreateProject } from "../BuildTools/Projects";
import {
	CompileContracts,
} from "../../Modules/Scripting/Source/Contracts/Index.ts";
import {
	ScriptsWasmPlugin, type RunCommand,
} from "../BuildTools/ScriptsWasmPlugin";

/** A project folder with these files (relative path -> text). */
function Project( files: Record<string, string> ): string {
	const directory = mkdtempSync( join( tmpdir(), "cse-contracts-" ) );

	for ( const [path, text] of Object.entries( files ) ) {
		mkdirSync( join( directory, path, ".." ), { recursive: true } );
		writeFileSync( join( directory, path ), text );
	}
	return directory;
}

const Score = "namespace Game;\ncontract IScore { Add( points: int ); }\n";

afterEach( () => {
	vi.restoreAllMocks();
} );

describe( "a project's .contract files at build time", () => {
	it(
		"are compiled next to themselves (TypeScript; C# with C# scripts), "
			+ "written only when changed; outputs of removed ones go",
		() => {
			const directory = Project( {
				"Source/Contracts/Score.contract": Score,
				"Source/Old.contract.ts":
				"// Generated from a .contract file by the engine (old)\n",
				"Source/Old.contract.cs": "// <auto-generated>\n",
				"Source/Mine.contract.ts": "// not generated: kept\n",
				"Source/obj/Skipped.contract": "this is not even valid",
			} );

			expect( GenerateContracts( directory, false ) ).toEqual( {
				Written: ["Source/Contracts/Score.contract.ts"],
				Removed: ["Source/Old.contract.cs", "Source/Old.contract.ts"],
				Errors: [],
			} );
			expect( existsSync( join( directory, "Source/Mine.contract.ts" ) ) )
				.toBe( true );
			expect(
				readFileSync(
					join( directory, "Source/Contracts/Score.contract.ts" ),
					"utf8",
				),
			)
				.toContain( "Contract<IScore>( \"Game.IScore\" )" );
			expect( GenerateContracts( directory, true ).Written )
				.toEqual( ["Source/Contracts/Score.contract.cs"] );
			expect( GenerateContracts( directory, true ).Written )
				.toEqual( [] );

			writeFileSync(
				join( directory, "Source/Contracts/Score.contract" ),
				"contract IScore {",
			);
			expect( GenerateContracts( directory, true ) ).toEqual( {
				Written: [], Removed: [],
				Errors: [
					"Source/Contracts/Score.contract:1:18: Expected a method "
						+ "name, "
					+ "found the end of the file",
				],
			} );
			// a project without Source/ has none
			expect( GenerateContracts( Project( {} ), true ) )
				.toEqual( { Written: [], Removed: [], Errors: [] } );
		},
	);

	it(
		"the plugin fails a build on a problem, warns in development, and "
			+ "recompiles when a .contract changes",
		() => {
			const directory = Project(
				{ "Source/Score.contract": "contract {" },
			);
			const plugin = ContractsPlugin(
				{ Directory: directory, CSharp: false },
			);
			const configResolved = plugin.configResolved as (
				c: ResolvedConfig,
			) => void;
			const buildStart = plugin.buildStart as (
				this: { error( m: string ): void; warn( m: string ): void; },
			) => void;
			const context = { error: vi.fn(), warn: vi.fn() };

			configResolved( { command: "build" } as ResolvedConfig );
			buildStart.call( context );
			expect( context.error.mock.lastCall![0] )
				.toContain(
					"Source/Score.contract:1:10: Expected a contract name",
				);
			configResolved( { command: "serve" } as ResolvedConfig );
			buildStart.call( context );
			expect( context.warn ).toHaveBeenCalledTimes( 1 );

			const listeners: ( ( file: string ) => void )[] = [];
			const logger = { info: vi.fn(), error: vi.fn() };
			const send = vi.fn();
			( plugin.configureServer as ( s: ViteDevServer ) => void )( {
				watcher: {
					add: vi.fn(),
					on: ( _: string, listener: ( file: string ) => void ) => (
						listeners.push( listener )
					),
				},
				config: { logger },
				ws: { send },
			} as unknown as ViteDevServer );
			expect( listeners ).toHaveLength( 3 );
			listeners[1]!( join( directory, "Source/Score.contract" ) );
			expect( send.mock.lastCall![0].type ).toBe( "error" );
			writeFileSync( join( directory, "Source/Score.contract" ), Score );
			// not a contract: nothing
			listeners[1]!( join( directory, "Source/Other.ts" ) );
			expect( logger.info ).not.toHaveBeenCalled();
			listeners[1]!( join( directory, "Source/Score.contract" ) );
			expect( logger.info )
				.toHaveBeenCalledWith(
					"contracts: wrote Source/Score.contract.ts",
				);
			// nothing changed: quiet
			listeners[1]!( join( directory, "Source/Score.contract" ) );
			expect( logger.info ).toHaveBeenCalledTimes( 1 );
			buildStart.call( context );
			expect( context.warn ).toHaveBeenCalledTimes( 1 );
		},
	);

	it(
		"the C# scripts aren't built while the .contract files have problems; "
			+ "they are generated first",
		() => {
			const directory = Project(
				{
					"Game.csproj": "<Project />",
					"Source/Score.contract": "contract {",
				},
			);
			const run = vi.fn<RunCommand>(
				() => ( { status: 0, stdout: "", stderr: "" } ),
			);
			const logger = { info: vi.fn(), error: vi.fn() };
			const plugin = ScriptsWasmPlugin(
				{ Directory: directory, CSharp: "Game.csproj", Run: run },
			);
			( plugin.configResolved as ( c: ResolvedConfig ) => void )(
				{
					command: "build",
					logger,
					root: directory,
					build: { outDir: "dist" },
				} as unknown as ResolvedConfig,
			);
			( plugin.writeBundle as () => void )();
			expect( run ).not.toHaveBeenCalled();
			expect( logger.error.mock.lastCall![0] )
				.toContain(
					"Game.csproj was not built - the .contract files have "
						+ "problems:",
				);
			writeFileSync( join( directory, "Source/Score.contract" ), Score );
			( plugin.writeBundle as () => void )();
			expect( run ).toHaveBeenCalled();
			expect(
				existsSync( join( directory, "Source/Score.contract.cs" ) ),
			)
				.toBe( true );
		},
	);
} );

describe( "the templates' contracts", () => {
	const Templates = join( import.meta.dirname, "../../../Templates" );

	it(
		"their generated files are up to date (the engine writes them whenever "
			+ "a .contract changes)",
		() => {
			for ( const template of [
				"Blank",
				"CoinHunt",
				"FirstPerson",
				"ThirdPerson",
				"TopDown",
			] ) {
				const directory = join( Templates, template );
				const contracts = ( readdirSync(
					join( directory, "Source" ),
					{ recursive: true, encoding: "utf8" },
				) )
					.filter( ( path ) => path.endsWith( ".contract" ) )
					.map(
						( path ) => `Source/${ path.replaceAll( "\\", "/" ) }`,
					);
				const result = CompileContracts(
					contracts.map(
						( path ) => ( {
							Path: path,
							Text: readFileSync(
								join( directory, path ),
								"utf8",
							),
						} ),
					),
					{ CSharp: true },
				);

				expect( result.Diagnostics, template ).toEqual( [] );
				for ( const output of result.Outputs ) {
					expect( output.Text, `${ template }/${ output.Path }` )
						.toBe(
							readFileSync(
								join( directory, output.Path ),
								"utf8",
							),
						);
				}
			}
		},
	);

	it(
		"a project made from Coin Hunt gets its own namespace in the contract "
			+ "and the generated code (nothing left to regenerate)",
		() => {
			const sandbox = mkdtempSync(
				join( tmpdir(), "cse-contract-project-" ),
			);
			const created = CreateProject( {
				TemplatesDirectory: Templates,
				Template: "CoinHunt",
				Name: "Moonrise",
				Location: sandbox,
				Registry: join( sandbox, "Projects.json" ),
			} );

			expect(
				readFileSync(
					join(
						created.Directory,
						"Source/Contracts/CoinHunt.contract",
					),
					"utf8",
				),
			).toContain( "namespace Moonrise;" );
			expect(
				readFileSync(
					join(
						created.Directory,
						"Source/Contracts/CoinHunt.contract.ts",
					),
					"utf8",
				),
			).toContain( "\"Moonrise.IRound\"" );
			expect( GenerateContracts( created.Directory, true ) )
				.toEqual( { Written: [], Removed: [], Errors: [] } );
		},
	);
} );
